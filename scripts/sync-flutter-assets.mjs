// sync-flutter-assets.mjs — models/manifest.json is the single source of truth (CLAUDE.md); the
// Flutter package (flutter/) is not allowed a second copy that can drift from it. This script IS
// the sync: it copies the frozen models, every non-pending head, manifest.json, LICENSE, and
// NOTICE from the repo root into flutter/, and regenerates flutter/lib/src/version.dart from
// flutter/pubspec.yaml (Dart has no API for a package to know its own version at runtime — see
// specs/2026-08-19-flutter-lib-pub-dev.md FR-7).
//
// Run:          node scripts/sync-flutter-assets.mjs          # writes
// Run (CI/gate): node scripts/sync-flutter-assets.mjs --check  # verifies, exits 1 on drift, writes nothing
//
// The synced files are committed, not gitignored (pub.dev follows no symlinks — a symlinked model
// would publish silently absent — and a gitignored copy would make `dart pub publish --dry-run`
// lie). This script is what keeps a committed copy honest instead of hand-maintained.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, copyFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const check = process.argv.includes('--check');
const fail = [];

const modelsDir = join(ROOT, 'models');
const flutterDir = join(ROOT, 'flutter');
const assetsDir = join(flutterDir, 'assets', 'models');

const manifest = JSON.parse(readFileSync(join(modelsDir, 'manifest.json'), 'utf8'));
const shared = ['melspectrogram.onnx', 'embedding_model.onnx'];
const heads = manifest.filter((m) => !m.pending).map((m) => m.file);
const expectedFiles = ['manifest.json', ...shared, ...heads];

function sameBytes(a, b) {
  if (!existsSync(a) || !existsSync(b)) return false;
  return Buffer.compare(readFileSync(a), readFileSync(b)) === 0;
}

function syncFile(srcDir, name, destDir) {
  const src = join(srcDir, name);
  const dest = join(destDir, name);
  if (check) {
    if (!sameBytes(src, dest)) fail.push(`stale or missing: ${dest.replace(ROOT, '')}`);
    return;
  }
  mkdirSync(destDir, { recursive: true });
  copyFileSync(src, dest);
}

// ---- models/manifest.json + shared models + every non-pending head ----
if (!check) mkdirSync(assetsDir, { recursive: true });
syncFile(modelsDir, 'manifest.json', assetsDir);
for (const f of shared) syncFile(modelsDir, f, assetsDir);
for (const f of heads) syncFile(modelsDir, f, assetsDir);

// ---- prune anything in flutter/assets/models/ the manifest doesn't name ----
if (existsSync(assetsDir)) {
  for (const f of readdirSync(assetsDir)) {
    if (expectedFiles.includes(f)) continue;
    if (check) fail.push(`stray file (manifest doesn't name it): flutter/assets/models/${f}`);
    else { console.log(`  removing stray asset: ${f}`); rmSync(join(assetsDir, f)); }
  }
}

// ---- LICENSE + NOTICE, byte-identical ----
syncFile(ROOT, 'LICENSE', flutterDir);
syncFile(ROOT, 'NOTICE', flutterDir);

// ---- flutter/lib/src/version.dart, generated from flutter/pubspec.yaml's version: ----
const pubspecPath = join(flutterDir, 'pubspec.yaml');
const versionDartPath = join(flutterDir, 'lib', 'src', 'version.dart');
if (existsSync(pubspecPath)) {
  const pubspec = readFileSync(pubspecPath, 'utf8');
  const m = pubspec.match(/^version:\s*(\S+)\s*$/m);
  if (!m) {
    fail.push('flutter/pubspec.yaml has no version: line');
  } else {
    const version = m[1];
    const expected =
      `// GENERATED by scripts/sync-flutter-assets.mjs from flutter/pubspec.yaml — do not hand-edit.\n` +
      `const wakekitVersion = '${version}';\n`;
    if (check) {
      const actual = existsSync(versionDartPath) ? readFileSync(versionDartPath, 'utf8') : null;
      if (actual !== expected) fail.push(`stale: flutter/lib/src/version.dart (pubspec says ${version})`);
    } else {
      mkdirSync(join(flutterDir, 'lib', 'src'), { recursive: true });
      writeFileSync(versionDartPath, expected);
    }
  }
} else if (check) {
  fail.push('flutter/pubspec.yaml not found — run `flutter create` first');
}

if (check) {
  if (fail.length) {
    console.error(`sync-flutter-assets --check: ${fail.length} drift(s) found:`);
    for (const f of fail) console.error(`  - ${f}`);
    console.error('\nrun `node scripts/sync-flutter-assets.mjs` to fix.');
    process.exit(1);
  }
  console.log(`sync-flutter-assets --check: clean (${expectedFiles.length} model files, LICENSE, NOTICE, version.dart all match)`);
} else {
  console.log(`synced ${expectedFiles.length} model file(s), LICENSE, NOTICE, version.dart → flutter/`);
}
